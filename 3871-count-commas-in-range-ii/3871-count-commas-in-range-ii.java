class Solution {
    public long countCommas(long n) {
        long ans = 0;
        if(n<1000){
            ans = 0;
        }else if(n<1000000){
            ans = n-999;
        }else if(n<1000000000){
            ans = (999999-1000+1)+(n-999999)*2;
        }else if(n<1000000000000L){
            ans = (999999-1000+1)+(999999999-1000000+1)*2+(n-999999999L)*3;
        }else if(n < 1000000000000000L){
            ans = (999999-1000+1)+(999999999L-1000000+1)*2+(999999999999L-1000000000L+1)*3+(n-999999999999L)*4;
        }else{
            ans =  (999999-1000+1)+(999999999L-1000000+1)*2+(999999999999L-1000000000L+1)*3+(999999999999999L-1000000000000L+1)*4 +(n-999999999999999L)*5;
        }
        
        return ans;
    }
}